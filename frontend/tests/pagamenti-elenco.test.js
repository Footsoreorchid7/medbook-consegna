import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createMemoryHistory } from 'vue-router'
import App from '../src/App.vue'
import { createAppRouter } from '../src/router/index.js'
import { createSession, STATO } from '../src/session/session.js'
import { SESSION_KEY } from '../src/session/useSession.js'
import { prenotazioniStore } from '../src/prenotazioni/store.js'
import { parseAppuntamento } from '../src/api/prenotazioni.js'
import { confermata, pagamento, fallito } from './b4-fixtures.js'
import { CSRF_B, installFetch, jsonResponse, meOk, routedFetch, utente } from './helpers.js'

const ME = 'GET /api/auth/me'
const LISTA = 'GET /api/prenotazioni/paziente?idPaziente=7'
const PAG = 'GET /api/prenotazioni/12/pagamenti'
const POST = 'POST /api/prenotazioni/12/pagamento-online'
const LOGOUT = 'POST /api/auth/logout'
let net, wrapper
beforeEach(() => { net = installFetch(routedFetch()) })
afterEach(() => { wrapper?.unmount(); wrapper = null; vi.unstubAllGlobals() })
async function monta(path = '/paziente/prenotazioni', storico = jsonResponse(200, [])) {
  net.on(ME, meOk())
  net.on(LISTA, jsonResponse(200, [confermata()]))
  if (storico) net.on(PAG, storico)
  const session = createSession()
  const router = createAppRouter({ session, history: createMemoryHistory() })
  await router.push(path)
  await router.isReady()
  wrapper = mount(App, { global: { plugins: [router], provide: { [SESSION_KEY]: session } }, attachTo: document.body })
  await flushPromises()
  return { session, router, store: prenotazioniStore(session) }
}
const button = text => wrapper.findAll('button').find(b => b.text() === text)
const click = async b => { b.element.focus(); await b.trigger('click'); await flushPromises() }
const vai = async (router, path) => { await router.push(path); await flushPromises() }
const summaryPath = '/paziente/prenotazioni/12/pagamenti/5/riepilogo'

describe('pagamento dall’elenco con la conferma condivisa', () => {
  it('Paga adesso apre il riepilogo nell’elenco; nessuna POST prima di confermare', async () => {
    const { router } = await monta()
    expect(button('Paga adesso')).toBeDefined()
    await click(button('Paga adesso'))
    const c = wrapper.get('[data-conferma-pagamento]')
    expect(c.text()).toContain('Prenotazione n. 12')
    expect(c.text()).toContain('80,00')
    expect(c.text()).toContain('nessun denaro reale')
    expect(c.text()).toContain('2026')
    expect(document.activeElement).toBe(c.get('h3').element)
    expect(net.callsTo(POST)).toHaveLength(0)
    expect(router.currentRoute.value.name).toBe('prenotazioni')
    await click(button('Non pagare'))
    expect(document.activeElement).toBe(button('Paga adesso').element)
  })
  it.each(['PAGATO', 'IN_ATTESA'])('non propone un nuovo pagamento con storico %s', async stato => {
    await monta(undefined, jsonResponse(200, [pagamento(5, { stato, pagatoIl: stato === 'PAGATO' ? '2026-10-16T10:00:00' : null })]))
    expect(button('Paga adesso')).toBeUndefined()
    expect(net.callsTo(POST)).toHaveLength(0)
    expect(wrapper.find(`a[href="${summaryPath}"]`).exists()).toBe(stato === 'PAGATO')
  })
  it('lettura fallita: recupero manuale prima di proporre il pagamento', async () => {
    await monta(undefined, jsonResponse(500, {}))
    expect(button('Paga adesso')).toBeUndefined()
    expect(wrapper.get('[role="alert"]').text()).toContain('caricare i pagamenti')
    net.on(PAG, jsonResponse(200, []))
    await click(button('Riprova'))
    expect(button('Paga adesso')).toBeDefined()
    expect(net.callsTo(POST)).toHaveLength(0)
  })
  it('doppio clic bloccato; PAGATO invalida subito; riletture trattenute non riabilitano azioni', async () => {
    await monta()
    await click(button('Paga adesso'))
    const post = net.trattieni(POST)
    const c = button('Conferma pagamento simulato')
    await c.trigger('click'); await c.trigger('click')
    expect(net.callsTo(POST)).toHaveLength(1)
    expect(JSON.parse(net.callsTo(POST)[0].body)).toEqual({ importoAtteso: 80 })
    const lista = net.trattieni(LISTA), storico = net.trattieni(PAG)
    post.resolve(jsonResponse(201, pagamento(5)))
    await flushPromises()
    expect(button('Paga adesso')).toBeUndefined()
    expect(wrapper.find('[data-aggiornamento]').exists()).toBe(true)
    lista.resolve(jsonResponse(200, [confermata()]))
    await flushPromises()
    expect(button('Paga adesso')).toBeUndefined()
    storico.resolve(jsonResponse(200, [pagamento(5)]))
    await flushPromises()
    expect(wrapper.find(`a[href="${summaryPath}"]`).exists()).toBe(true)
    expect(net.callsTo(POST)).toHaveLength(1)
  })
  it('FALLITO richiede aggiornamento completo e una nuova conferma esplicita', async () => {
    await monta()
    await click(button('Paga adesso'))
    net.on(POST, jsonResponse(201, fallito(5)))
    const lista = net.trattieni(LISTA), storico = net.trattieni(PAG)
    await click(button('Conferma pagamento simulato'))
    expect(button('Paga adesso')).toBeUndefined()
    lista.resolve(jsonResponse(200, [confermata()]))
    await flushPromises()
    storico.resolve(jsonResponse(200, [fallito(5)]))
    await flushPromises()
    expect(button('Paga adesso')).toBeDefined()
    expect(wrapper.find('[data-conferma-pagamento]').exists()).toBe(false)
    expect(net.callsTo(POST)).toHaveLength(1)
  })
  it('rilettura prenotazione fallita: Riprova recupera anche la prenotazione, senza nuovo POST', async () => {
    await monta()
    await click(button('Paga adesso'))
    net.on(POST, jsonResponse(201, fallito(5))).on(LISTA, jsonResponse(500, {})).on(PAG, jsonResponse(200, [fallito(5)]))
    await click(button('Conferma pagamento simulato'))
    expect(button('Paga adesso')).toBeUndefined()
    net.on(LISTA, jsonResponse(200, [confermata()])).on(PAG, jsonResponse(200, [fallito(5)]))
    await click(button('Riprova'))
    expect(button('Paga adesso')).toBeDefined()
    expect(net.callsTo(LISTA)).toHaveLength(3)
    expect(net.callsTo(POST)).toHaveLength(1)
  })
  it('incertezza conservata navigando: verifica manuale, mai reinvio automatico', async () => {
    const { router } = await monta()
    await click(button('Paga adesso'))
    net.on(POST, 'rete')
    await click(button('Conferma pagamento simulato'))
    expect(wrapper.get('[data-pagamento-incerto]').text()).toContain('non è possibile un nuovo tentativo')
    await vai(router, '/area')
    net.on(LISTA, jsonResponse(200, [confermata()])).on(PAG, jsonResponse(200, []))
    await vai(router, '/paziente/prenotazioni')
    expect(button('Paga adesso')).toBeUndefined()
    net.on(PAG, jsonResponse(200, []), jsonResponse(200, []))
    await click(button('Verifica nello storico pagamenti'))
    expect(wrapper.get('[data-pagamento-incerto]').text()).toContain('Questo non prova')
    expect(button('Nuovo tentativo di pagamento simulato')).toBeDefined()
    expect(net.callsTo(POST)).toHaveLength(1)
  })
  it('scrittura vecchia istanza: successo condiviso sospende la nuova vista già caricata', async () => {
    const { router } = await monta()
    await click(button('Paga adesso'))
    const post = net.trattieni(POST)
    await button('Conferma pagamento simulato').trigger('click')
    await vai(router, '/area')
    net.on(LISTA, jsonResponse(200, [confermata()])).on(PAG, jsonResponse(200, []))
    await vai(router, '/paziente/prenotazioni')
    expect(button('Paga adesso').attributes('disabled')).toBeDefined()
    post.resolve(jsonResponse(201, pagamento(5)))
    await flushPromises()
    expect(button('Paga adesso')).toBeUndefined()
    expect(wrapper.text()).not.toContain('Pagamento simulato riuscito:')
    expect(button('Aggiorna lo storico')).toBeDefined()
    expect(net.callsTo(POST)).toHaveLength(1)
  })
  it('storico vecchio dopo scrittura certa non diventa idoneo; recupero successivo disponibile', async () => {
    const pending = net.trattieni(PAG)
    const { session, store } = await monta(undefined, null)
    net.on(POST, jsonResponse(201, fallito(5)))
    expect((await store.pagaOnline(parseAppuntamento(confermata(), 7), [])).kind).toBe('fallito')
    pending.resolve(jsonResponse(200, []))
    await flushPromises()
    expect(button('Paga adesso')).toBeUndefined()
    net.on(LISTA, jsonResponse(200, [confermata()])).on(PAG, jsonResponse(200, [fallito(5)]))
    await click(button('Riprova'))
    expect(button('Paga adesso')).toBeDefined()
    expect(session.state.status).toBe(STATO.AUTENTICATO)
  })
  it('store: uno storico precedente a FALLITO non autorizza una seconda POST', async () => {
    const { store } = await monta()
    const ticket = store.inizioLettura()
    expect(store.registraStorico(12, [], ticket)).toBe(true)
    net.on(POST, jsonResponse(201, fallito(5)))
    expect((await store.pagaOnline(parseAppuntamento(confermata()), [], ticket)).kind).toBe('fallito')
    expect((await store.pagaOnline(parseAppuntamento(confermata()), [], ticket)).kind).toBe('dati-superati')
    expect(net.callsTo(POST)).toHaveLength(1)
  })
  it('rotazione durante la lettura: la vecchia risposta non ripristina pagamento o dati superati', async () => {
    const vecchia = net.trattieni(PAG)
    const { session } = await monta(undefined, null)
    net.on('PUT /api/auth/password', jsonResponse(200, { message: 'ok', nuovoAccessoRichiesto: false }, { 'X-CSRF-Token': CSRF_B }))
    net.on(LISTA, jsonResponse(200, [confermata(12, { prezzo: 99 })])).on(PAG, jsonResponse(200, []))
    expect((await session.changePassword('precedente', 'nuova')).kind).toBe('aggiornata')
    await flushPromises()
    vecchia.resolve(jsonResponse(200, [pagamento(5)]))
    await flushPromises()
    await click(button('Paga adesso'))
    expect(wrapper.get('[data-conferma-pagamento]').text()).toContain('99,00')
    expect(wrapper.find('a[href="' + summaryPath + '"]').exists()).toBe(false)
    expect(net.callsTo(POST)).toHaveLength(0)
  })
  it('password incerta impedisce il POST, anche dal gestore', async () => {
    const { session } = await monta()
    net.on('PUT /api/auth/password', 'rete')
    await session.changePassword('precedente', 'nuova')
    await flushPromises()
    expect(button('Paga adesso')?.attributes('disabled')).toBeDefined()
    expect(net.callsTo(POST)).toHaveLength(0)
  })
})

describe('riepilogo autorizzato e stampabile', () => {
  it.each(['ONLINE', 'DESK_POS', 'DESK_CONTANTI'])('dati autentici %s e testo non fiscale coerente', async modalita => {
    await monta(summaryPath, jsonResponse(200, [pagamento(5, { modalita })]))
    const doc = wrapper.get('[data-riepilogo-pagamento]')
    expect(doc.text()).toContain('Documento dimostrativo non fiscale.')
    expect(doc.text()).toContain('n. 12')
    expect(doc.text()).toContain('n. 5')
    expect(doc.text()).toContain('80,00')
    expect(doc.text()).toContain('non attesta l’esecuzione'.replace('’', "'"))
    expect(doc.text()).not.toMatch(/IBAN|partita IVA|fattura/i)
    expect(doc.text().includes('Nessuna transazione bancaria reale è stata eseguita.')).toBe(modalita === 'ONLINE')
    if (modalita !== 'ONLINE') expect(doc.text()).toContain('non esegue né certifica una transazione POS')
    const print = vi.fn(); vi.stubGlobal('print', print)
    await click(button('Stampa / Salva come PDF'))
    expect(print).toHaveBeenCalledOnce()
    expect(localStorage.length + sessionStorage.length).toBe(0)
  })
  it('anche il dettaglio propone lo stesso riepilogo per un pagamento PAGATO', async () => {
    await monta('/paziente/prenotazioni/12', jsonResponse(200, [pagamento(5)]))
    expect(wrapper.get('[data-sezione="pagamenti"] a[href="' + summaryPath + '"]').text()).toContain('Scarica riepilogo (stampa / PDF)')
    expect(button('Paga online (simulato)')).toBeUndefined()
  })
  it('logout dal riepilogo elimina immediatamente i dati e termina sulla home', async () => {
    const { session, router } = await monta(summaryPath, jsonResponse(200, [pagamento(5)]))
    expect(wrapper.find('[data-riepilogo-pagamento]').exists()).toBe(true)
    const logout = net.trattieni(LOGOUT)
    const promessa = session.logout()
    await flushPromises()
    expect(wrapper.find('[data-riepilogo-pagamento]').exists()).toBe(false)
    logout.resolve(jsonResponse(200, { message: 'ok' }))
    await promessa
    await vi.waitFor(() => expect(router.currentRoute.value.name).toBe('home'))
    expect(wrapper.find('[data-riepilogo-pagamento]').exists()).toBe(false)
  })
  it('nessun documento per pagamento non pagato; nessuna scrittura', async () => {
    await monta(summaryPath, jsonResponse(200, [fallito(5)]))
    expect(wrapper.find('[data-riepilogo-pagamento]').exists()).toBe(false)
    expect(wrapper.text()).toContain('Riepilogo non disponibile')
    expect(net.callsTo(POST)).toHaveLength(0)
  })
  it('errore di lettura recuperabile senza documento parziale', async () => {
    await monta(summaryPath, jsonResponse(500, {}))
    expect(wrapper.find('[data-riepilogo-pagamento]').exists()).toBe(false)
    net.on(LISTA, jsonResponse(200, [confermata()])).on(PAG, jsonResponse(200, [pagamento(5)]))
    await click(button('Riprova'))
    expect(wrapper.find('[data-riepilogo-pagamento]').exists()).toBe(true)
    expect(document.activeElement).toBe(wrapper.get('[data-riepilogo-pagamento] h1').element)
  })
  it('cambio risorsa A → B → A: nessuna adozione tardiva', async () => {
    const a = net.trattieni(PAG)
    const { router } = await monta(summaryPath, null)
    net.on(LISTA, jsonResponse(200, [confermata()])).on(PAG, jsonResponse(200, [pagamento(6)]))
    await vai(router, '/paziente/prenotazioni/12/pagamenti/6/riepilogo')
    net.on(LISTA, jsonResponse(200, [confermata()])).on(PAG, jsonResponse(200, [pagamento(5, { importo: 75 })]))
    await vai(router, summaryPath)
    a.resolve(jsonResponse(200, [pagamento(5, { importo: 100 })]))
    await flushPromises()
    expect(wrapper.get('[data-riepilogo-pagamento]').text()).toContain('75,00')
    expect(wrapper.get('[data-riepilogo-pagamento]').text()).not.toContain('100,00')
  })
})

describe('destinazione logout', () => {
  it('successo verso home con notifica; incertezza resta al recupero', async () => {
    const { session, router } = await monta()
    net.on(LOGOUT, jsonResponse(500, {}))
    await session.logout(); await flushPromises()
    expect(session.state.status).toBe(STATO.LOGOUT_NON_CONFERMATO)
    expect(router.currentRoute.value.name).not.toBe('home')
    net.on(ME, meOk(utente(), CSRF_B)).on(LOGOUT, jsonResponse(200, { message: 'ok' }))
    await session.recoverLogout()
    await vi.waitFor(() => expect(router.currentRoute.value.name).toBe('home'))
    await flushPromises()
    expect(wrapper.find('[aria-label="Chiudi avviso"]').exists()).toBe(true)
  })
})
