describe('creazione', () => {
  it('conferma senza password; payload con i soli campi previsti; password cancellata; nessun accesso del nuovo utente', async () => {
    await apriPagina()
    await compilaCrea()
    const conferma = wrapper.get('[data-conferma="crea"]')
    expect(attivo()).toBe(wrapper.get('#titolo-conferma-crea').element)
    expect(conferma.get('[data-campo="email"]').text()).toBe('nina@example.test')
    expect(conferma.text()).not.toContain(PASSWORD)
    net.on(CREA, jsonResponse(201, account(20, { nome: 'Nina', cognome: 'Nuova', email: 'nina@example.test' }))).on(GESTIONALI, jsonResponse(200, [account(1), account(20)]))
    await click(bottoneIn(conferma, 'Crea account'))
    expect(JSON.parse(net.callsTo(CREA)[0].body)).toEqual({ nome: 'Nina', cognome: 'Nuova', email: 'nina@example.test', password: PASSWORD, ruoloGestionale: 'OPERATORE_DESK' })
    expect(avviso()).toContain('Account n. 20 creato')
    expect(avviso()).toContain('Nessun accesso automatico')
    expect(wrapper.get('#nuovo-password').element.value).toBe('')
    expect(wrapper.get('#nuovo-email').element.value).toBe('')
    expect(document.body.innerHTML).not.toContain(PASSWORD)
    expect(net.calls.some((c) => c.url === '/api/auth/login')).toBe(false)
    expect(net.callsTo(GESTIONALI)).toHaveLength(2)
  })

  it('409 email presente: password cancellata, altri campi conservati, nessun retry', async () => {
    await apriPagina()
    await compilaCrea()
    net.on(CREA, jsonResponse(409, { error: 'Email già presente.' })).on(GESTIONALI, jsonResponse(200, [account(1)]))
    await click(bottoneIn(wrapper.get('[data-conferma="crea"]'), 'Crea account'))
    expect(avviso()).toContain('Email già presente.')
    expect(avviso()).toContain('La password è stata cancellata dal modulo')
    expect(wrapper.get('#nuovo-password').element.value).toBe('')
    expect(wrapper.get('#nuovo-email').element.value).toBe('Nina@Example.test')
    expect(net.callsTo(CREA)).toHaveLength(1)
  })

  it('incerta: blocco della stessa email, verifica manuale per email senza attribuzione, poi nuovo tentativo solo esplicito', async () => {
    const { router } = await apriPagina()
    await compilaCrea()
    net.on(CREA, 'rete')
    await click(bottoneIn(wrapper.get('[data-conferma="crea"]'), 'Crea account'))
    expect(avviso()).toContain("Non è stato possibile stabilire l'esito")
    expect(wrapper.get('#nuovo-password').element.value).toBe('')
    await router.push('/area')
    await flushPromises()
    net.on(GESTIONALI, jsonResponse(200, [account(1)]))
    await router.push(PG)
    await flushPromises()
    await compilaCrea()
    expect(wrapper.get('[data-errori-crea]').text()).toContain('ancora da verificare')
    expect(wrapper.find('[data-conferma="crea"]').exists()).toBe(false)
    net.on(RICERCA('email=nina%40example.test&limite=50'), jsonResponse(200, pagina([amministrativo(20, { email: 'nina@example.test' })])))
    net.on(GESTIONALI, jsonResponse(200, [account(1), account(20)]))
    await click(bottoneIn(wrapper.get('[data-esito-incerto]'), 'Verifica'))
    expect(avviso()).toContain("esiste l'account n. 20")
    expect(avviso()).toContain('non prova che sia stato creato dal tentativo')
    expect(wrapper.find('[data-esito-incerto]').exists()).toBe(false)
    expect(net.callsTo(CREA)).toHaveLength(1)
  })
})

