import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createMemoryHistory } from 'vue-router'
import App from '../src/App.vue'
import { parseAccount } from '../src/api/utenti.js'
import { adminStore } from '../src/admin/store.js'
import { createAppRouter } from '../src/router/index.js'
import { createSession } from '../src/session/session.js'
import { SESSION_KEY } from '../src/session/useSession.js'
import { CREA, GESTIONALI, PASSWORD, RICERCA, RUOLO, STATO, account, admin, amministrativo, desk, pagina } from './admin-utenti-fixtures.js'
import { CSRF_B, installFetch, jsonResponse, meOk, routedFetch, utente } from './helpers.js'

const ME = 'GET /api/auth/me'
const PWD = 'PUT /api/auth/password'
const PG = '/admin/utenti'
let net
let wrapper
beforeEach(() => { net = installFetch(routedFetch()) })
afterEach(() => {
  wrapper?.unmount()
  wrapper = null
  vi.restoreAllMocks()
  vi.useRealTimers()
})

async function mountApp(path, user = admin()) {
  net.on(ME, meOk(user))
  const session = createSession()
  const router = createAppRouter({ session, history: createMemoryHistory() })
  router.push(path)
  await router.isReady()
  wrapper = mount(App, { global: { plugins: [router], provide: { [SESSION_KEY]: session } }, attachTo: document.body })
  await flushPromises()
  await vi.waitFor(() => expect(router.currentRoute.value.matched.length).toBeGreaterThan(0))
  await flushPromises()
  return { session, router, store: adminStore(session) }
}
const apriPagina = (voci = [account(1, { ruoloGestionale: 'AMMINISTRATORE' }), account(5)]) => {
  net.on(GESTIONALI, jsonResponse(200, voci))
  return mountApp(PG)
}
const bottoneIn = (w, testo) => w.findAll('button').find((b) => b.text().startsWith(testo))
const click = async (b) => { await b.trigger('click'); await flushPromises() }
const attivo = () => document.activeElement
const avviso = () => wrapper.get('[data-avviso-admin]').text()
const riga = (sel, id) => wrapper.get(`${sel}[data-id="${id}"]`)
const gestionale = (id) => riga('[data-gestionale]', id)
const risultato = (id) => riga('[data-risultato]', id)
const scritture = () => net.calls.filter((c) => c.method !== 'GET' && !c.url.startsWith('/api/auth')).length
const cerca = async (campi) => {
  for (const [sel, v] of Object.entries(campi)) await wrapper.get(sel).setValue(v)
  await wrapper.get('form').trigger('submit')
  await flushPromises()
}
async function compilaCrea({ nome = 'Nina', cognome = 'Nuova', email = 'Nina@Example.test', password = PASSWORD, ruolo = 'OPERATORE_DESK' } = {}) {
  if (!wrapper.find('#nuovo-nome').exists()) await click(wrapper.get('[data-apri-account]'))
  await wrapper.get('#nuovo-nome').setValue(nome)
  await wrapper.get('#nuovo-cognome').setValue(cognome)
  await wrapper.get('#nuovo-email').setValue(email)
  await wrapper.get('#nuovo-password').setValue(password)
  if (ruolo) await wrapper.get(`input[name="nuovo-ruolo"][value="${ruolo}"]`).setValue(true)
  await click(bottoneIn(wrapper.get('#modulo-nuovo-account form'), 'Prosegui'))
}

